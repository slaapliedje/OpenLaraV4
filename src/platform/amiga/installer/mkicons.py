PEN = {'.': 0, '#': 1, 'o': 2, '+': 3}


def planes(art):
    h, w = len(art), max(len(r) for r in art)
    rowbytes = (w + 15) // 16 * 2
    out = bytearray()
    for plane in range(2):
        for y in range(h):
            row = bytearray(rowbytes)
            for x, ch in enumerate(art[y]):
                if PEN[ch] >> plane & 1:
                    row[x >> 3] |= 0x80 >> (x & 7)
            out += row
    return w, h, bytes(out)


def diskobject(art, kind, stack=16384):
    w, h, data = planes(art)
    NO_POS = 0x80000000
    gadget = struct.pack('>IhhhhHHHIIIIIHI', 0, 0, 0, w, h + 1, 0x0004, 0x0003, 0x0001,
                         1, 0, 0, 0, 0, 0, 1)                       # GADGIMAGE (complement highlight), OS 2 revision
    dobj = struct.pack('>HH', 0xE310, 1) + gadget + struct.pack('>BBIIIIIII', kind, 0, 0, 0, NO_POS, NO_POS,
                                                                1 if kind == 2 else 0, 0, stack)
    out = dobj
    if kind == 2:                                                   # drawer: its window (NewWindow + position)
        out += struct.pack('>hhhhBBIIIIIIIhhHHH', 50, 50, 400, 200, 255, 255, 0, 0, 0, 0, 0, 0, 0,
                           90, 40, 0xFFFF, 0xFFFF, 1) + struct.pack('>ii', 0, 0)
    out += struct.pack('>hhhhhIBBI', 0, 0, w, h, 2, 1, 3, 0, 0) + data
    if kind == 2:
        out += struct.pack('>IH', 0, 0)                            # OS 2 drawer data: flags, view modes (defaults)
    return out


if __name__ == '__main__':
    here = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'icons')
    os.makedirs(here, exist_ok=True)
    for name, art, kind in (('OpenLara.info', LAUNCHER, 3), ('Drawer.info', DRAWER, 2)):
        with open(os.path.join(here, name), 'wb') as f:
            f.write(diskobject(art, kind))
        print(name, os.path.getsize(os.path.join(here, name)))
