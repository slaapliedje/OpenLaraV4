"""mkicons.py: OpenLara's Workbench icons (classic DiskObject, 4 colours, readable by every AmigaOS) drawn
from the pixel art below. Writes icons/OpenLara.info (tool icon for the launchers) and icons/Drawer.info.
Pens: '.' 0 background grey, '#' 1 black, 'o' 2 white, '+' 3 blue (the Workbench's first four colours)."""
